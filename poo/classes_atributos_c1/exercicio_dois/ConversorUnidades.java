package poo.classes_atributos_c1.exercicio_dois;

public class ConversorUnidades {
    
    public static final double FATOR_MILHAS_PARA_METROS = 1609.34;

    public static double milhasParaMetros(double milhas) {
        return milhas * FATOR_MILHAS_PARA_METROS;
    }

    public static int somar(int a, int b) {
        return a + b;
    }
}
